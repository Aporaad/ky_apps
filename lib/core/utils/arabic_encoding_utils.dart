  };

  /// إصلاح وترجمة أي نص عربي مشوه فورياً
  static String fix(dynamic input) {
    if (input == null) return '';
    final str = input.toString().trim();
    if (str.isEmpty) return str;

    final runes = str.runes;
    var hasMojibake = false;
    for (final r in runes) {
      if (r >= 0x80 && r <= 0xFF && _cp1256Map.containsKey(r)) {
        hasMojibake = true;
        break;
      }
    }

    if (!hasMojibake) return str;

    final buffer = StringBuffer();
    for (final r in runes) {
      if (r >= 0x80 && r <= 0xFF && _cp1256Map.containsKey(r)) {
        buffer.write(_cp1256Map[r]);
      } else {
        buffer.writeCharCode(r);
      }
    }
    return buffer.toString();
  }
}
